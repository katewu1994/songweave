export const DICTS: Record<Lang, Dict> = { en, ja };

export const LangContext = createContext<Dict>(en);
export const useT = () => useContext(LangContext);

export function viewName(t: Dict, v: ViewId | string): string {
  return (t as unknown as Record<string, string>)[`view_${v}`] ?? (v === "cross_view" ? t.dimLabel_cross_view : v);
}
export function viewDesc(t: Dict, v: ViewId): string {
  return (t as unknown as Record<string, string>)[`viewDesc_${v}`] ?? "";
}
export function lyricsStatus(t: Dict, s: string): string {
  return (t as unknown as Record<string, string>)[`lyr_${s}`] ?? s;
}
export function reasonText(t: Dict, reason: string): string {
  if (reason === "full") return t.reason_full;
  if (reason === "not_analyzed") return t.reason_not_analyzed;
  if (reason.startsWith("coverage_")) return t.reason_partial;
  if (reason.startsWith("lyrics_")) return lyricsStatus(t, reason.slice(7));
  return reason;
}

export function initialLang(): Lang {
  try {
    const s = window.localStorage.getItem("songweave.lang");
    if (s === "en" || s === "ja") return s;
  } catch {
    /* storage unavailable */
  }
  return "en";
}
export function saveLang(l: Lang) {
  try {
    window.localStorage.setItem("songweave.lang", l);
  } catch {
    /* storage unavailable */
  }
}
